-- ---------------------------------------------------------------------
-- 0. Clean slate (children first, so foreign keys don't block the drops)
-- ---------------------------------------------------------------------
drop table if exists listing_reports, notifications, payments, password_resets,
    audit_logs, admin_actions, viewings, inquiries, favourites,
    property_images, properties, agent_profiles, users cascade;
drop function if exists set_updated_at() cascade;

-- ---------------------------------------------------------------------
-- 1. users: every account (client, agent, admin, super admin)
-- ---------------------------------------------------------------------
create table users (
    user_id               integer generated by default as identity primary key,
    full_name             varchar(100) not null,
    email                 varchar(150) not null unique check (email = lower(email)),
    phone                 varchar(15)  not null unique,
    password_hash         varchar(255) not null,
    role                  varchar(20)  not null check (role in ('client', 'agent', 'admin', 'super_admin')),
    account_status        varchar(20)  not null default 'active' check (account_status in ('active', 'suspended')),
    must_change_password  boolean      not null default false,
    twofa_enabled         boolean      not null default false,
    twofa_secret          text,                                   -- encrypted by the backend, never plain text
    failed_logins         smallint     not null default 0 check (failed_logins >= 0),
    locked_until          timestamptz,
    last_login_at         timestamptz,
    created_at            timestamptz  not null default now(),
    updated_at            timestamptz  not null default now()
);
comment on table users is 'All accounts. Role decides what each user may do.';

-- ---------------------------------------------------------------------
-- 2. agent_profiles: extra details for agents (1:1 with users)
-- ---------------------------------------------------------------------
create table agent_profiles (
    agent_id             integer primary key references users(user_id) on delete cascade,
    licence_no           varchar(30)  not null unique,
    agency_name          varchar(100),
    bio                  varchar(500),
    verification_status  varchar(20)  not null default 'pending'
                         check (verification_status in ('pending', 'approved', 'rejected')),
    rejection_reason     varchar(255),
    verified_by          integer references users(user_id) on delete set null,
    verified_at          timestamptz
);
comment on table agent_profiles is 'Licence and verification details; only approved agents may list properties.';

-- ---------------------------------------------------------------------
-- 3. properties: listings posted by agents
-- ---------------------------------------------------------------------
create table properties (
    property_id     integer generated by default as identity primary key,
    agent_id        integer      not null references agent_profiles(agent_id) on delete cascade,
    title           varchar(150) not null,
    description     text,
    listing_type    varchar(10)  not null check (listing_type in ('sale', 'rent')),
    property_type   varchar(20)  not null check (property_type in ('apartment', 'house', 'land', 'commercial')),
    price           numeric(12,2) not null check (price > 0),
    bedrooms        smallint     not null default 0 check (bedrooms between 0 and 50),
    bathrooms       smallint     not null default 0 check (bathrooms between 0 and 50),
    location        varchar(100) not null,
    address         varchar(255),
    listing_status  varchar(20)  not null default 'available'
                    check (listing_status in ('available', 'under_offer', 'sold', 'rented', 'removed')),
    featured_until  timestamptz,
    views_count     integer      not null default 0 check (views_count >= 0),
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now()
);
create index idx_properties_search   on properties (listing_status, listing_type, property_type, price);
create index idx_properties_location on properties (lower(location));
create index idx_properties_agent    on properties (agent_id);

-- ---------------------------------------------------------------------
-- 4. property_images: photos (composition: deleted with the property)
-- ---------------------------------------------------------------------
create table property_images (
    image_id     integer generated by default as identity primary key,
    property_id  integer      not null references properties(property_id) on delete cascade,
    image_url    varchar(500) not null,
    is_cover     boolean      not null default false,
    uploaded_at  timestamptz  not null default now()
);
create index idx_images_property on property_images (property_id);
-- At most one cover photo per property
create unique index uq_images_one_cover on property_images (property_id) where is_cover;

-- ---------------------------------------------------------------------
-- 5. favourites: client <-> property junction table (M:N)
-- ---------------------------------------------------------------------
create table favourites (
    client_id    integer     not null references users(user_id) on delete cascade,
    property_id  integer     not null references properties(property_id) on delete cascade,
    saved_at     timestamptz not null default now(),
    primary key (client_id, property_id)
);

-- ---------------------------------------------------------------------
-- 6. inquiries: questions from clients, replies from agents
-- ---------------------------------------------------------------------
create table inquiries (
    inquiry_id      integer generated by default as identity primary key,
    client_id       integer     not null references users(user_id) on delete cascade,
    property_id     integer     not null references properties(property_id) on delete cascade,
    message         text        not null check (char_length(message) between 10 and 1000),
    agent_reply     text,
    inquiry_status  varchar(20) not null default 'open' check (inquiry_status in ('open', 'replied', 'closed')),
    created_at      timestamptz not null default now(),
    replied_at      timestamptz
);
create index idx_inquiries_client   on inquiries (client_id);
create index idx_inquiries_property on inquiries (property_id, inquiry_status);

-- ---------------------------------------------------------------------
-- 7. viewings: THE MAIN TRANSACTION (booking a property viewing)
-- ---------------------------------------------------------------------
create table viewings (
    viewing_id      integer generated by default as identity primary key,
    client_id       integer     not null references users(user_id) on delete cascade,
    property_id     integer     not null references properties(property_id) on delete cascade,
    scheduled_at    timestamptz not null check (extract(minute from scheduled_at) = 0),  -- whole-hour slots
    viewing_status  varchar(20) not null default 'requested'
                    check (viewing_status in ('requested', 'confirmed', 'rescheduled', 'declined', 'completed', 'cancelled')),
    agent_note      varchar(255),
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now()
);
-- Double-booking guard: a property can hold only ONE live booking per time slot.
-- "Partial" index = it only covers live bookings, so declined/cancelled slots free up again.
create unique index uq_viewings_live_slot on viewings (property_id, scheduled_at)
    where viewing_status in ('requested', 'confirmed', 'rescheduled');
-- A client can hold only ONE live booking per property.
create unique index uq_viewings_live_client on viewings (client_id, property_id)
    where viewing_status in ('requested', 'confirmed', 'rescheduled');
create index idx_viewings_schedule on viewings (scheduled_at, viewing_status);

-- ---------------------------------------------------------------------
-- 8. admin_actions: formal record of every moderation decision
-- ---------------------------------------------------------------------
create table admin_actions (
    action_id           integer generated by default as identity primary key,
    admin_id            integer     not null references users(user_id),   -- no cascade: history must survive
    action_type         varchar(30) not null check (action_type in (
                          'approve_agent', 'reject_agent', 'suspend_user', 'reinstate_user',
                          'remove_listing', 'restore_listing', 'reset_password', 'disable_2fa',
                          'create_user', 'delete_user', 'change_role')),
    target_user_id      integer references users(user_id) on delete set null,
    target_property_id  integer references properties(property_id) on delete set null,
    reason              varchar(255),
    created_at          timestamptz not null default now()
);
create index idx_admin_actions_created on admin_actions (created_at);

-- ---------------------------------------------------------------------
-- 9. audit_logs: who did what, when, from where
-- ---------------------------------------------------------------------
create table audit_logs (
    log_id       bigint generated by default as identity primary key,
    user_id      integer references users(user_id) on delete set null,  -- null = anonymous (e.g. failed login)
    action       varchar(50)  not null,
    entity_type  varchar(30),
    entity_id    integer,
    details      varchar(500),
    ip_address   varchar(45),
    user_agent   varchar(255),
    created_at   timestamptz  not null default now()
);
create index idx_audit_user    on audit_logs (user_id);
create index idx_audit_created on audit_logs (created_at);
create index idx_audit_action  on audit_logs (action);

-- ---------------------------------------------------------------------
-- 10. payments: M-Pesa STK Push or admin-reviewed manual requests
-- ---------------------------------------------------------------------
create table payments (
    payment_id           integer generated by default as identity primary key,
    agent_id             integer       not null references agent_profiles(agent_id) on delete cascade,
    property_id          integer       references properties(property_id) on delete set null,
    payment_method       varchar(20)   not null default 'manual'
                         constraint payments_payment_method_check check (payment_method in ('manual', 'mpesa')),
    phone                varchar(15),
    merchant_request_id  varchar(60),
    checkout_request_id  varchar(60),
    payment_reference    varchar(100),
    amount               numeric(10,2) not null check (amount > 0),
    feature_days         smallint      not null check (feature_days > 0),
    payment_status       varchar(20)   not null default 'pending'
                         check (payment_status in ('pending', 'success', 'failed', 'cancelled')),
    result_desc          varchar(255),
    created_at           timestamptz   not null default now(),
    updated_at           timestamptz   not null default now(),
    constraint payments_mpesa_needs_phone check (payment_method <> 'mpesa' or phone is not null)
);
create index idx_payments_agent on payments (agent_id);
create unique index uq_payments_checkout_request on payments (checkout_request_id) where checkout_request_id is not null;

-- ---------------------------------------------------------------------
-- 11. notifications: in-app alerts (bell icon)
-- ---------------------------------------------------------------------
create table notifications (
    notification_id  integer generated by default as identity primary key,
    user_id          integer      not null references users(user_id) on delete cascade,
    message          varchar(255) not null,
    link             varchar(255),
    is_read          boolean      not null default false,
    created_at       timestamptz  not null default now()
);
create index idx_notifications_user on notifications (user_id, is_read);

-- ---------------------------------------------------------------------
-- 12. listing_reports: clients flag suspicious listings for admins
-- ---------------------------------------------------------------------
create table listing_reports (
    report_id      integer generated by default as identity primary key,
    property_id    integer      not null references properties(property_id) on delete cascade,
    reporter_id    integer      not null references users(user_id) on delete cascade,
    reason         varchar(255) not null check (char_length(reason) >= 10),
    report_status  varchar(20)  not null default 'open' check (report_status in ('open', 'resolved')),
    created_at     timestamptz  not null default now()
);
create index idx_reports_status on listing_reports (report_status);

-- ---------------------------------------------------------------------
-- Trigger: keep updated_at current automatically (MySQL's ON UPDATE has no
-- direct PostgreSQL equivalent, so one small trigger function does it).
-- ---------------------------------------------------------------------
create function set_updated_at() returns trigger
language plpgsql as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

create trigger trg_users_updated      before update on users      for each row execute function set_updated_at();
create trigger trg_properties_updated before update on properties for each row execute function set_updated_at();
create trigger trg_viewings_updated   before update on viewings   for each row execute function set_updated_at();
create trigger trg_payments_updated   before update on payments   for each row execute function set_updated_at();
