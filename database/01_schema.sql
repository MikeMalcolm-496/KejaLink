-- =====================================================================
--  KejaLink: Property Listing and Viewing Management System
--  SCRIPT 1 of 3: tables, constraints, indexes and the updated_at trigger
--  Target: Supabase (PostgreSQL 15+). Paste into Supabase > SQL Editor > Run.
--
--  Safe to re-run: it drops the KejaLink tables first (THIS DELETES THEIR DATA).
--  Order of execution: 01_schema.sql -> 02_security_and_storage.sql -> 03_demo_data.sql
